"""Generate explicit on/off/restart contracts for every boolean preference.

The generated tests use only temporary Hive boxes. Preference persistence is
one audit layer; controller and widget tests separately verify actual effects.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
sources = [
    ('PlaybackPrefs', 'lib/core/playback/playback_prefs.dart'),
    ('ReaderPrefs', 'lib/core/reading/reader_prefs.dart'),
]
out = ["// Generated by tool/generate_boolean_settings_tests.py. Tests every boolean",
       "// setting in both states and after reopening its isolated storage box.",
       "import 'dart:io';", "import 'package:flutter_test/flutter_test.dart';",
       "import 'package:hive/hive.dart';"]
for _, path in sources:
    out.append(f"import 'package:watch_app/{path[4:]}';")
out += ["", "/// Checks persistence without reading or changing the user's settings.",
        "void main() {", "  late Directory directory;",
        "  setUp(() async {", "    directory = await Directory.systemTemp.createTemp('settings-contract-');",
        "    Hive.init(directory.path);", "    await PlaybackPrefs.init();", "    await ReaderPrefs.init();", "  });",
        "  tearDown(() async {", "    await Hive.close();", "    await directory.delete(recursive: true);", "  });"]
count = 0
for cls, path in sources:
    source = (root / path).read_text(encoding='utf8')
    getters = set(re.findall(r'bool\s+get\s+(\w+)', source))
    setters = re.findall(r'(?:Future<void>|void)\s+(set\w+)\(bool\s+\w+\)', source)
    for setter in setters:
        getter = setter[3].lower() + setter[4:]
        if getter not in getters:
            continue
        count += 1
        out += [f"  test('{cls}.{getter}: on, off, and restart', () async {{",
                f"    final prefs = {cls}();",
                "    for (final value in [true, false]) {",
                f"      await prefs.{setter}(value);",
                f"      expect(prefs.{getter}, value);",
                f"      await Hive.box({cls}.boxName).flush();",
                f"      await Hive.box({cls}.boxName).close();",
                f"      await {cls}.init();",
                f"      expect({cls}().{getter}, value, reason: 'Survives reopening storage');",
                "    }", "  });"]
out.append('}')
destination = root / 'test/desktop/boolean_settings_contract_test.dart'
destination.parent.mkdir(exist_ok=True)
destination.write_text('\n'.join(out) + '\n', encoding='utf8')
print(f'Boolean preference contracts generated: {count}')
